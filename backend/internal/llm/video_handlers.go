package llm

// video_handlers.go implements the OpenAI-Sora-style async video surface:
//
//	POST /v1/videos       -> submit an upstream job, return a job object
//	GET  /v1/videos/:id    -> poll: proxy-poll the upstream, update + return
//
// Billing: submit takes a Reserve hold for the job's estimated maximum cost
// (last-request / 0.25 water-line; available <= 0 is rejected before any
// upstream job is launched). Video holds do not occupy the llm:/ws: last-
// request slot. Exact settle may take the balance negative; CapAtHold does
// not. Completion settles that hold against the upstream-reported duration
// in ONE transaction that also claims generation_tasks.billed, so "charge
// succeeded" and "billed=true" cannot diverge. A failed job releases the
// hold — natural refund. A succeeded job whose settle fails stays
// non-terminal so the reconciler retries it.

