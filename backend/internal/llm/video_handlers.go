// videoHoldKey ties a video job's submit-time reservation to its completion
// settle. The task UUID is generated by the server before Reserve and then
// persisted on Create, so a client-controlled X-Request-Id cannot make two
// jobs share one hold.
func videoHoldKey(taskID uuid.UUID) string { return "video:" + taskID.String() }

// requestedVideoSeconds extracts the client-requested clip duration from a
// Sora-style body ("seconds" comes as a string enum in OpenAI's API, but a
// bare number is accepted too). 0 = not specified, which makes the reserve
// estimator fall back to its own default.
func requestedVideoSeconds(body map[string]any) int {
	for _, key := range []string{"seconds", "duration"} {
		switch v := body[key].(type) {
		case float64:
			if v > 0 {
				return int(v)
			}
		case string:
			if n, err := strconv.Atoi(strings.TrimSpace(v)); err == nil && n > 0 {
				return n
			}
		}
	}
	return 0
}

// handleVideoCreate submits an async video job and returns a job object.
func (g *Gateway) handleVideoCreate(c *gin.Context) {
	startedAt := time.Now()
	requestID := gatewayRequestID(c)
	ep := entusagelog.EndpointVideoGeneration
	writeErr := func(status int, errKind, code, message string) {
		c.JSON(status, openAIError(errKind, code, message, requestID))
	}

	user, ok := middleware.UserFrom(c)
	if !ok {
		writeErr(http.StatusUnauthorized, "authentication_error", "missing_user", "no user")
		return
	}
	apiKey, _ := middleware.ApiKeyFrom(c)

	raw, err := g.readLimitedBody(c)
	if err != nil {
		writeErr(http.StatusRequestEntityTooLarge, "invalid_request_error", "request_body_too_large", "request body too large")
		return
	}
	var body map[string]any
	if err := json.Unmarshal(raw, &body); err != nil {
		writeErr(http.StatusBadRequest, "invalid_request_error", "invalid_json", "body must be valid JSON")
		return
	}
	modelName, _ := body["model"].(string)
	if modelName == "" {
		writeErr(http.StatusBadRequest, "invalid_request_error", "missing_model", "missing model")
		return
	}

	reqCtx := c.Request.Context()

	// Input policy scan (same dictionary + block semantics as chat).
	if g.policy != nil {
		scan := g.policy.Scan(biz.RedactImagesForScan(raw))
		if block, _ := scan.BlockDecision(); block {
			writeErr(http.StatusUnprocessableEntity, "content_policy_violation", "input_policy_block", "blocked by input moderation policy")
			return
		}
	}

	route, err := g.models.Resolve(reqCtx, modelName, user, apiKey, biz.RequestProtocolOpenAI)
	// Video is not account-aware yet: the submit path resolves the
	// channel-level credential, and the poll/reconciler paths key off the task
	// rather than the attempt, so expanding candidates here would only
	// duplicate attempts against the same key (and drop channels whose
	// accounts are all parked). Wire it end to end before enabling.
	if err != nil {
		if errors.Is(err, biz.ErrNoProvider) {
			g.recordNoProviderAvailability(reqCtx, err, requestID, modelName, ep, startedAt)
		}
		g.writeRouteError(writeErr, modelName, err)
		return
	}
	if err := g.models.CheckAccess(reqCtx, user, apiKey, route.Group); err != nil {
		g.recordRouteAvailability(reqCtx, route.Group.ID, requestID, modelName, ep, entavailability.OutcomeExcluded, biz.AvailabilityFailureAccess, http.StatusForbidden, startedAt)
		writeErr(http.StatusForbidden, "permission_error", "access_denied", err.Error())
		return
	}
	// Precheck billing eligibility up front (reject users who can't pay);
	// the actual charge happens on completion, metered by duration.
	planState, err := g.billing.ResolvePlanState(reqCtx, user, apiKey, route.Group)
	if err != nil {
		outcome, failureClass, status := billingRouteAvailability(err)
		g.recordRouteAvailability(reqCtx, route.Group.ID, requestID, modelName, ep, outcome, failureClass, status, startedAt)
		g.writeBillingError(c, writeErr, err)
		return
	}

	// Reserve the job's estimated maximum cost before launching anything
	// upstream. The long TTL covers slow renders; completion settles the
	// hold against the reported duration, failure releases it.
	taskID := uuid.New()
	estCost := g.billing.EstimateMaxCost(reqCtx, route.Model, route.Group, biz.CostEstimateInput{
		BodyBytes:     len(raw),
		OutputSeconds: requestedVideoSeconds(body),
	})
	reservation, resErr := g.billing.Reserve(reqCtx, biz.ReserveInput{
		User: user, ApiKey: apiKey, Group: route.Group, PlanState: planState,
		Key: videoHoldKey(taskID), Amount: estCost, TTL: biz.ReserveTTLVideo,
		Note: "video generation reserve " + requestID,
	})
	if resErr != nil {
		outcome, failureClass, status := billingRouteAvailability(resErr)
		g.recordRouteAvailability(reqCtx, route.Group.ID, requestID, modelName, ep, outcome, failureClass, status, startedAt)
		g.writeBillingError(c, writeErr, resErr)
		return
	}

	// Pick the first routed provider that has an async-video adaptor.
	// Each Submit is a failover attempt and is recorded as one; the poll
	// path is not, because a client polling every second would otherwise
	// drown the counter in status reads.
	var lastErr error
	adaptorFound := false
	for _, rp := range route.Providers {
		format := ProviderFormat(rp.Account)
		ad := videoAdaptorFor(format)
		if ad == nil {
			continue
		}
		adaptorFound = true
		key, err := g.accounts.RequestToken(reqCtx, rp.Account)
		if err != nil {
			lastErr = err
			metrics.LLMAttemptsTotal.WithLabelValues(metricOwner(rp), string(ep), string(classUnknown)).Inc()
			continue
		}
		encoded, err := prepareForwardBody(body, rp.UpstreamModel, false)
		if err != nil {
			lastErr = err
			metrics.LLMAttemptsTotal.WithLabelValues(metricOwner(rp), string(ep), string(classUnknown)).Inc()
			continue
		}
		attemptStage := time.Now()
		sub, err := ad.Submit(reqCtx, rp.Account.BaseURL, key, rp.UpstreamModel, encoded)
		metrics.LLMAttemptDuration.WithLabelValues(metricOwner(rp), string(ep)).Observe(time.Since(attemptStage).Seconds())
		if err != nil {
			lastErr = err
			metrics.LLMAttemptsTotal.WithLabelValues(metricOwner(rp), string(ep), string(classProviderFailure)).Inc()
			metrics.LLMRetriesTotal.WithLabelValues(route.Group.ID.String(), string(classProviderFailure)).Inc()
			continue
		}
		metrics.LLMAttemptsTotal.WithLabelValues(metricOwner(rp), string(ep), string(classOK)).Inc()

		// Persist the task (billed=false). Billing is settled on COMPLETION
		// (per-second, from the upstream's reported duration), so a job that
		// fails is never charged — natural refund. The precheck above already
		// rejected users who can't pay.
		task, err := g.tasks.Create(reqCtx, biz.CreateTaskInput{
			ID:     taskID,
			UserID: user.ID, ApiKeyID: apiKeyID(apiKey), OrganizationID: organizationID(apiKey),
			RequestID: requestID, Endpoint: string(ep), Model: modelName,
			// The task carries the ACCOUNT id: the poll path (here and in the
			// reconciler) resolves it with g.accounts.Get, and an account
			// created after the migration has no legacy channel id at all.
			GroupID: &route.Group.ID, ProviderID: accountIDRef(rp.Account), UpstreamModel: rp.UpstreamModel,
			ProviderFormat: format, UpstreamTaskID: sub.UpstreamTaskID,
		})
		if err != nil {
			// The upstream job may be running, but with no task row it can
			// never be settled — return the hold instead of stranding it.
			g.releaseReservation(reqCtx, reservation)
			g.recordRouteAvailability(reqCtx, route.Group.ID, requestID, modelName, ep, entavailability.OutcomeBad, biz.AvailabilityFailureInternal, http.StatusInternalServerError, startedAt)
			writeErr(http.StatusInternalServerError, "api_error", "task_persist_failed", "failed to persist generation task")
			return
		}
		c.JSON(http.StatusOK, videoJobJSON(task, ""))
		return
	}

	// Nothing was submitted — return the hold.
	g.releaseReservation(reqCtx, reservation)
	if !adaptorFound {
		g.recordRouteAvailability(reqCtx, route.Group.ID, requestID, modelName, ep, entavailability.OutcomeBad, "endpoint_unsupported", http.StatusServiceUnavailable, startedAt)
		writeErr(http.StatusServiceUnavailable, "service_unavailable", "endpoint_unsupported_by_providers",
			"no provider for model "+modelName+" supports async video generation")
		return
	}
	msg := "upstream unavailable"
	if lastErr != nil {
		msg = lastErr.Error()
	}
	g.recordRouteAvailability(reqCtx, route.Group.ID, requestID, modelName, ep, entavailability.OutcomeBad, "provider_failure", http.StatusBadGateway, startedAt)
	writeErr(http.StatusBadGateway, "upstream_error", "video_submit_failed", msg)
}

// HandleVideoGet implements GET /v1/videos/:id — poll a job.
func (g *Gateway) HandleVideoGet(c *gin.Context) {
	requestID := gatewayRequestID(c)
	writeErr := func(status int, errKind, code, message string) {
		c.JSON(status, openAIError(errKind, code, message, requestID))
	}
	if g.tasks == nil {
		writeErr(http.StatusNotImplemented, "api_error", "async_not_implemented", "video task store not available")
		return
	}
	user, ok := middleware.UserFrom(c)
	if !ok {
		writeErr(http.StatusUnauthorized, "authentication_error", "missing_user", "no user")
		return
	}
	id, err := uuid.Parse(c.Param("id"))
	if err != nil {
		writeErr(http.StatusBadRequest, "invalid_request_error", "invalid_id", "invalid task id")
		return
	}
	reqCtx := c.Request.Context()
	task, err := g.tasks.Get(reqCtx, id)
	if err != nil || task.UserID != user.ID {
		// Same 404 for missing and not-owned, to avoid leaking existence.
		writeErr(http.StatusNotFound, "invalid_request_error", "task_not_found", "task not found")
		return
	}

	// Failed tasks are returned from storage. Succeeded ones are polled
	// again because the video URL is never stored; live ones advance.
	if task.Status == entgentask.StatusFailed {
		c.JSON(http.StatusOK, videoJobJSON(task, ""))
		return
	}
	ad := videoAdaptorFor(task.ProviderFormat)
	if ad == nil || task.ProviderID == nil || task.UpstreamTaskID == "" {
		c.JSON(http.StatusOK, videoJobJSON(task, ""))
		return
	}
	acct, err := g.accounts.Get(reqCtx, *task.ProviderID)
	if err != nil {
		c.JSON(http.StatusOK, videoJobJSON(task, ""))
		return
	}
	key, err := g.accounts.RequestToken(reqCtx, acct)
	if err != nil {
		c.JSON(http.StatusOK, videoJobJSON(task, ""))
		return
	}
	poll, err := ad.Poll(reqCtx, acct.BaseURL, key, task.UpstreamTaskID)
	if err != nil {
		// Transient poll failure: return the last known state.
		c.JSON(http.StatusOK, videoJobJSON(task, ""))
		return
	}

	if task.Status != entgentask.StatusSucceeded {
		g.applyVideoPoll(reqCtx, task, poll)
	}
	videoURL := ""
	if task.Status == entgentask.StatusSucceeded && poll.Status == VideoStatusSucceeded {
		videoURL = poll.VideoURL
	}
	c.JSON(http.StatusOK, videoJobJSON(task, videoURL))
}

// applyVideoPoll advances a task from a poll result. Shared by the client GET
// path and the background reconciler. The passed task is mutated to reflect
// the new state so the caller can render it.
//
// On success, billing settles BEFORE the task turns terminal: settle failure
// leaves the task running, so the reconciler (and the client's next poll)
// retries — that is what makes "Charge succeeded" and "billed=true"
// effectively one retryable atom (they already share one transaction inside
// SettleReservation). On failure the submit hold is released: natural refund.
func (g *Gateway) applyVideoPoll(ctx context.Context, task *ent.GenerationTask, poll VideoPollResult) {
	switch poll.Status {
	case VideoStatusSucceeded:
		if !g.settleVideoCompletion(ctx, task, poll.BilledSeconds) {
			// Billing not settled (transient error, or a per-second model
			// with no reported duration). Keep the task non-terminal so it
			// is retried; the reconciler's max-age expiry bounds how long.
			if task.Status != entgentask.StatusRunning {
				_ = g.tasks.SetStatus(ctx, task.ID, VideoStatusRunning)
				task.Status = entgentask.StatusRunning
			}
			return
		}
		if err := g.tasks.Complete(ctx, task.ID, biz.CompleteInput{
			Status: VideoStatusSucceeded, BilledSeconds: poll.BilledSeconds,
		}); err != nil {
			return
		}
		task.Status = entgentask.StatusSucceeded
		task.BilledSeconds = poll.BilledSeconds
	case VideoStatusFailed:
		// No charge on failure — return the submit hold.
		g.releaseVideoHold(ctx, task)
		_ = g.tasks.Complete(ctx, task.ID, biz.CompleteInput{
			Status: VideoStatusFailed, ErrorMessage: poll.ErrorMessage,
		})
		task.Status = entgentask.StatusFailed
		task.ErrorMessage = biz.SanitizeTaskError(poll.ErrorMessage)
	case VideoStatusRunning:
		if task.Status != entgentask.StatusRunning {
			_ = g.tasks.SetStatus(ctx, task.ID, VideoStatusRunning)
			task.Status = entgentask.StatusRunning
		}
	}
}

// releaseVideoHold returns a task's submit-time reservation, if one is still
// held. Safe to call when no hold exists (plan-quota pseudo-holds, tasks from
// before reservations, already-finished holds).
func (g *Gateway) releaseVideoHold(ctx context.Context, task *ent.GenerationTask) {
	resv, err := g.billing.LoadHeldReservation(ctx, videoHoldKey(task.ID))
	if err != nil || resv == nil {
		return
	}
	g.releaseReservation(ctx, resv)
}

// settleVideoCompletion charges a succeeded video job exactly once, metered by
// the upstream-reported duration (per-second when the model sets
// output_second_price, otherwise the flat per_request base). Returns true when
// billing is finished (settled now, or already billed by a racer) and the task
// may turn terminal; false when the settle must be retried.
//
// Atomicity: for monetary holds the charge and generation_tasks.billed=true
// are ONE transaction (SettleReservation with TaskID); a crash between them is
// impossible. Plan-quota billing consumes a Redis window that cannot join the
// PG transaction, so there the billed flag is claimed first and the consume
// follows — same ordering as before this change.
func (g *Gateway) settleVideoCompletion(ctx context.Context, task *ent.GenerationTask, seconds int) bool {
	if task.Billed {
		return true
	}
	bc, err := g.tasks.LoadBillingContext(ctx, task)
	if err != nil || bc.Group == nil || bc.Model == nil {
		return false
	}
	// A per-second model with no reported duration must not settle at 0.
	// Refuse, warn, and leave the task pending (billed=false, hold open) so
	// a later poll that does carry the duration can settle for real. The
	// reconciler's max-age expiry eventually fails the task, which releases
	// the hold — bounded, and never a silent free render.
	if bc.Model.OutputSecondPrice != nil && seconds <= 0 {
		slog.Warn("video completion missing billed duration; billing left pending",
			"task_id", task.ID.String(), "request_id", task.RequestID, "model", task.Model)
		return false
	}
	base, final, err := g.billing.CalcCost(bc.Model, bc.Group, biz.TokenUsage{OutputSeconds: seconds})
	if err != nil {
		return false
	}

	// Find the submit-time hold. When it is gone (plan-quota pseudo-hold,
	// reaped by the expiry cleaner, or a task submitted before reservations
	// existed) take a fresh zero-amount hold: the settle then charges the
	// whole cost as over-hold extra, clamped at the live balance, still in
	// the same transaction that claims the billed flag.
	resv, err := g.billing.LoadHeldReservation(ctx, videoHoldKey(task.ID))
	if err != nil {
		return false
	}
	if resv == nil {
		resv, err = g.billing.Reserve(ctx, biz.ReserveInput{
			User: bc.User, ApiKey: bc.ApiKey, Group: bc.Group,
			Key: videoHoldKey(task.ID) + ":settle", Amount: decimal.Zero,
			TTL: biz.ReserveTTLVideo, Note: "video settle hold " + task.RequestID,
		})
		if err != nil {
			if errors.Is(err, biz.ErrHoldFinished) {
				// A previous settle finished this hold; the billed flag went
				// with it in the same transaction.
				task.Billed = true
				return true
			}
			return false
		}
	}

	var res *biz.ChargeResult
	var chargeErr error
	if resv.Monetary() {
		res, chargeErr = g.billing.SettleReservation(ctx, resv, base, final, biz.SettleOptions{
			Note:   "video generation settle " + task.RequestID,
			TaskID: &task.ID,
		})
		if errors.Is(chargeErr, biz.ErrTaskAlreadyBilled) {
			// A racer settled first; nothing moved in this transaction.
			task.Billed = true
			return true
		}
		if res == nil && chargeErr != nil {
			return false
		}
	} else {
		// Plan quota lives in Redis, so it cannot share the PG transaction.
		// Settle first through ConsumeQuotaOnce: its Redis marker makes a
		// crash/retry unable to increment twice. Only after successful
		// consumption may the durable billed flag be claimed.
		res, chargeErr = g.billing.SettleReservation(ctx, resv, base, final, biz.SettleOptions{
			Note: "video generation settle " + task.RequestID,
		})
		if chargeErr != nil {
			return false
		}
		won, err := g.tasks.MarkBilled(ctx, task.ID, final)
		if err != nil {
			return false
		}
		if !won {
			task.Billed = true
			return true
		}
	}
	task.Billed = true
	status := entusagelog.StatusOk
	errMsg := ""
	if chargeErr != nil {
		status = entusagelog.StatusInternalError
		errMsg = chargeErr.Error()
	}
	bs := entusagelog.BillingSourceNone
	orgID := task.OrganizationID
	var userPlanID *uuid.UUID
	costFinal := final
	if res != nil {
		bs = res.BillingSource
		if res.OrganizationID != nil {
			orgID = res.OrganizationID
		}
		userPlanID = res.UserPlanID
		costFinal = res.CostFinal
	}
	_, _ = g.billing.WriteUsageLog(ctx, biz.WriteUsageLogInput{
		UserID: task.UserID, ApiKeyID: task.APIKeyID, RequestID: task.RequestID,
		OrganizationID: orgID, Endpoint: entusagelog.EndpointVideoGeneration, Model: task.Model,
		ModelID: modelIDFromEntity(bc.Model), GroupID: task.GroupID, ProviderID: task.ProviderID, UpstreamModel: task.UpstreamModel,
		CostBase: base, CostFinal: costFinal, RateMultiplierApplied: bc.Group.RateMultiplier,
		Currency: biz.CurrencyCNY, BillingSource: bs, UserPlanID: userPlanID,
		Status: status, HTTPStatus: http.StatusOK, ErrorMessage: errMsg,
		StartedAt: task.CreatedAt, Delivered: true,
	})
	return true
}

// videoJobJSON renders a task as an OpenAI-Sora-style job object.
// videoJobJSON renders a task. videoURL comes from the poll that answered
// this request; it is not stored.
func videoJobJSON(t *ent.GenerationTask, videoURL string) gin.H {
	h := gin.H{
		"id":         t.ID.String(),
		"object":     "video.generation.job",
		"status":     string(t.Status),
		"model":      t.Model,
		"created_at": t.CreatedAt.Unix(),
	}
	if videoURL != "" {
		h["video_url"] = videoURL
	}
	if t.Status == entgentask.StatusSucceeded && t.BilledSeconds > 0 {
		h["seconds"] = t.BilledSeconds
	}
	if t.ErrorMessage != "" {
		h["error"] = gin.H{"message": t.ErrorMessage}
	}
	return h
}

